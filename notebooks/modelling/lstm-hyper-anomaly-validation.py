import sys

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import tensorflow as tf
from keras.callbacks import EarlyStopping
from keras_tuner import GridSearch
from sklearn.metrics import mean_pinball_loss

sys.path.append('../..')

from src.eagles_vezhen._helper_lstm_ae_functions import (
    lstm_ae,
    lstm_ae_hp,
)


eagles_x = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/eagles_x3.npy',
    allow_pickle=True,
)

vezhen_x = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/vezhen_x3.npy',
    allow_pickle=True,
)

eagles_y = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/eagles_y3.npy',
    allow_pickle=True,
).reshape((-1, 5, 3))

vezhen_y = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/vezhen_y3.npy',
    allow_pickle=True,
).reshape((-1, 5, 3))


tf.random.set_seed(42)


X_train = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/X_train2.npy'
)

y_train = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/y_train2.npy'
)

X_test = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/X_test2.npy'
)

y_test = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/y_test2.npy'
)

X_val = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/X_val2.npy'
)

y_val = np.load(
    '../../output/data_eagles_vezhen/lstm-ae/y_val2.npy'
)


train_dataset = (
    tf.data.Dataset
    .from_tensor_slices((X_train, y_train))
    .batch(64)
    .shuffle(buffer_size=10_000)
)

val_dataset = (
    tf.data.Dataset
    .from_tensor_slices((X_val, y_val))
    .batch(64)
    .shuffle(buffer_size=10_000)
)


# Lower-quantile hyperparameter search.
gs_low = GridSearch(
    hypermodel=lambda hp: lstm_ae_hp(
        tau=0.025,
        hp=hp,
        n_out_features=y_train.shape[2],
        n_out_timesteps=y_train.shape[1],
    ),
    objective='val_loss',
    directory='../../output/models/lstm-ae-08-08-1',
    project_name='lstm-ae-low',
)

best_low_params = gs_low.get_best_hyperparameters()[0].values

print('Best low-quantile hyperparameters:')
print(best_low_params)


model_low = lstm_ae(
    tau=0.025,
    n_out_features=3,
    n_out_timesteps=5,
    **best_low_params,
)

history_low = model_low.fit(
    train_dataset,
    validation_data=val_dataset,
    epochs=200,
    callbacks=EarlyStopping(patience=10),
)


# Upper-quantile hyperparameter search.
gs_high = GridSearch(
    hypermodel=lambda hp: lstm_ae_hp(
        tau=0.975,
        hp=hp,
        n_out_features=y_train.shape[2],
        n_out_timesteps=y_train.shape[1],
    ),
    objective='val_loss',
    directory='../../output/models/lstm-ae-08-08-1',
    project_name='lstm-ae-low',
)

best_high_params = gs_high.get_best_hyperparameters()[0].values

print('Best high-quantile hyperparameters:')
print(best_high_params)


model_high = lstm_ae(
    tau=0.975,
    n_out_features=3,
    n_out_timesteps=5,
    **best_high_params,
)

history_high = model_high.fit(
    train_dataset,
    validation_data=val_dataset,
    epochs=200,
    callbacks=EarlyStopping(patience=10),
)


# Lower-quantile model training history.
plt.plot(history_low.history['loss'], label='loss')
plt.plot(history_low.history['val_loss'], label='val_loss')
plt.legend()
plt.savefig('../images/eagles_vezhen_lstm_ae_low_training_history.png')
plt.close()


# Upper-quantile model training history.
plt.plot(history_high.history['loss'], label='loss')
plt.plot(history_high.history['val_loss'], label='val_loss')
plt.legend()
plt.savefig('../images/eagles_vezhen_lstm_ae_high_training_history.png')
plt.close()


eagles_output_high = model_high.predict(eagles_x)
eagles_output_low = model_low.predict(eagles_x)

vezhen_output_high = model_high.predict(vezhen_x)
vezhen_output_low = model_low.predict(vezhen_x)


# Eagles: delta COG prediction interval.
plt.plot(eagles_output_high[:, 0, 0])
plt.plot(eagles_output_low[:, 0, 0])
plt.plot(eagles_y[:, 0, 0])
plt.savefig('../images/eagles_prediction_interval_delta_cog.png')
plt.close()

eagles_delta_cog_coverage = np.mean(
    (eagles_y[:, :, 0] > eagles_output_low[:, :, 0])
    & (eagles_y[:, :, 0] < eagles_output_high[:, :, 0])
)

print(
    'Eagles delta_cog prediction interval coverage:',
    eagles_delta_cog_coverage,
)


# Eagles: delta DIF prediction interval.
plt.plot(eagles_output_high[:, 0, 1])
plt.plot(eagles_output_low[:, 0, 1])
plt.plot(eagles_y[:, 0, 1])
plt.savefig('../images/eagles_prediction_interval_delta_dif.png')
plt.close()

eagles_delta_dif_coverage = np.mean(
    (eagles_y[:, :, 1] > eagles_output_low[:, :, 1])
    & (eagles_y[:, :, 1] < eagles_output_high[:, :, 1])
)

print(
    'Eagles delta_dif prediction interval coverage:',
    eagles_delta_dif_coverage,
)


# Eagles: DIF prediction interval.
plt.plot(eagles_output_high[:, 0, 2])
plt.plot(eagles_output_low[:, 0, 2])
plt.plot(eagles_y[:, 0, 2])
plt.savefig('../images/eagles_prediction_interval_dif.png')
plt.close()

eagles_dif_coverage = np.mean(
    (eagles_y[:, :, 2] > eagles_output_low[:, :, 2])
    & (eagles_y[:, :, 2] < eagles_output_high[:, :, 2])
)

print(
    'Eagles dif prediction interval coverage:',
    eagles_dif_coverage,
)


# Vezhen: delta COG prediction interval.
plt.plot(vezhen_output_high[:, 0, 0])
plt.plot(vezhen_output_low[:, 0, 0])
plt.plot(vezhen_y[:, 0, 0])
plt.savefig('../images/vezhen_prediction_interval_delta_cog.png')
plt.close()

vezhen_delta_cog_coverage = np.mean(
    (vezhen_y[:, :, 0] > vezhen_output_low[:, :, 0])
    & (vezhen_y[:, :, 0] < vezhen_output_high[:, :, 0])
)

print(
    'Vezhen delta_cog prediction interval coverage:',
    vezhen_delta_cog_coverage,
)


# Vezhen: delta DIF prediction interval.
plt.plot(vezhen_output_high[:, 0, 1])
plt.plot(vezhen_output_low[:, 0, 1])
plt.plot(vezhen_y[:, 0, 1])
plt.savefig('../images/vezhen_prediction_interval_delta_dif.png')
plt.close()

vezhen_delta_dif_coverage = np.mean(
    (vezhen_y[:, :, 1] > vezhen_output_low[:, :, 1])
    & (vezhen_y[:, :, 1] < vezhen_output_high[:, :, 1])
)

print(
    'Vezhen delta_dif prediction interval coverage:',
    vezhen_delta_dif_coverage,
)


# Vezhen: DIF prediction interval.
plt.plot(vezhen_output_high[:, 0, 2])
plt.plot(vezhen_output_low[:, 0, 2])
plt.plot(vezhen_y[:, 0, 2])
plt.savefig('../images/vezhen_prediction_interval_dif.png')
plt.close()

vezhen_dif_coverage = np.mean(
    (vezhen_y[:, :, 2] > vezhen_output_low[:, :, 2])
    & (vezhen_y[:, :, 2] < vezhen_output_high[:, :, 2])
)

print(
    'Vezhen dif prediction interval coverage:',
    vezhen_dif_coverage,
)


# Calculate lower-quantile prediction and preserve the notebook's
# displayed pinball-loss result.
y_low = model_low.predict(X_test)

lower_pinball_loss = mean_pinball_loss(
    y_test[:, 0, 0],
    y_low[:, 0, 0],
    alpha=0.025,
)

print(
    'Lower-quantile pinball loss for first output/time step:',
    lower_pinball_loss,
)


# Calculate test-set prediction intervals and evaluation metrics.
y_high = model_high.predict(X_test)

picp_res = np.mean(
    (y_test < y_high) & (y_test > y_low),
    axis=0,
)

pinaw_res = np.mean(
    np.abs(y_high - y_low),
    axis=0,
)

loss_low_res = mean_pinball_loss(
    y_test.reshape((-1, 15)),
    y_low.reshape((-1, 15)),
    alpha=0.025,
    multioutput='raw_values',
)

loss_high_res = mean_pinball_loss(
    y_test.reshape((-1, 15)),
    y_high.reshape((-1, 15)),
    alpha=0.975,
    multioutput='raw_values',
)


df_picp = pd.DataFrame(
    picp_res,
    columns=['delta_cog', 'delta_dif', 'dif'],
)

df_picp['time_step'] = list(range(5, 30, 5))

print('\nPICP:')
print(df_picp)


df_pinaw = pd.DataFrame(
    pinaw_res,
    columns=['delta_cog', 'delta_dif', 'dif'],
)

df_pinaw['time_step'] = list(range(5, 30, 5))

print('\nPINAW:')
print(df_pinaw)


df_loss_low = pd.DataFrame(
    loss_low_res.reshape((5, 3)),
    columns=['delta_cog', 'delta_dif', 'dif'],
)

df_loss_low['time_step'] = list(range(5, 30, 5))

print('\nLow-quantile pinball loss:')
print(df_loss_low)


df_loss_high = pd.DataFrame(
    loss_high_res.reshape((5, 3)),
    columns=['delta_cog', 'delta_dif', 'dif'],
)

df_loss_high['time_step'] = list(range(5, 30, 5))

print('\nHigh-quantile pinball loss:')
print(df_loss_high)


# Save all evaluation CSV files under ../../output/.
df_picp.to_csv(
    '../../output/data_eagles_vezhen/lstm-ae/picp-lstm.csv'
)

df_pinaw.to_csv(
    '../../output/data_eagles_vezhen/lstm-ae/pinaw-lstm.csv'
)

df_loss_low.to_csv(
    '../../output/data_eagles_vezhen/lstm-ae/loss_low-lstm.csv'
)

df_loss_high.to_csv(
    '../../output/data_eagles_vezhen/lstm-ae/loss_high-lstm.csv'
)


# Calculate validation-set prediction interval coverage.
y_val_low = model_low.predict(X_val)
y_val_high = model_high.predict(X_val)

val_mmsis = np.load(
    '../../output/data_eagles_vezhen2/val-mmsis.npy',
    allow_pickle=True,
)

val_days = np.load(
    '../../output/data_eagles_vezhen2/val-days.npy',
    allow_pickle=True,
)

in_pi_mask = (y_val > y_val_low) & (y_val < y_val_high)
in_pi_mask = in_pi_mask.reshape((-1, 5, 3))

group_results = {}

for ix, (mmsi, day) in enumerate(zip(val_mmsis, val_days)):
    group_results.setdefault(
        (mmsi, day),
        [],
    ).append(in_pi_mask[ix])


df = []

for (mmsi, day), pi_masks in group_results.items():
    means = np.array(pi_masks).mean(axis=1).mean(axis=0)

    df.append(
        {
            'mmsi': mmsi,
            'day': day,
            'delta_cog': means[0],
            'delta_dif': means[1],
            'dif': means[2],
        }
    )

df = pd.DataFrame(df)

thresh_delta_cog = np.quantile(
    df['delta_cog'],
    0.05,
)

thresh_delta_dif = np.quantile(
    df['delta_dif'],
    0.05,
)

thresh_dif = np.quantile(
    df['dif'],
    0.05,
)

print('delta_cog limit:', thresh_delta_cog)
print('delta_dif limit:', thresh_delta_dif)
print('dif limit:', thresh_dif)


# Calculate test-set prediction interval coverage.
in_pi_mask = (y_test > y_low) & (y_test < y_high)
in_pi_mask = in_pi_mask.reshape((-1, 5, 3))

test_mmsis = np.load(
    '../../output/data_eagles_vezhen2/test-mmsis.npy',
    allow_pickle=True,
)

test_days = np.load(
    '../../output/data_eagles_vezhen2/test-days.npy',
    allow_pickle=True,
)

group_results = {}

for ix, (mmsi, day) in enumerate(zip(test_mmsis, test_days)):
    group_results.setdefault(
        (mmsi, day),
        [],
    ).append(in_pi_mask[ix])


df = []

for (mmsi, day), pi_masks in group_results.items():
    means = np.array(pi_masks).mean(axis=1).mean(axis=0)

    df.append(
        {
            'mmsi': mmsi,
            'day': day,
            'delta_cog': means[0],
            'delta_dif': means[1],
            'dif': means[2],
        }
    )

df = pd.DataFrame(df)


print(
    'Test delta_cog below threshold:',
    (df['delta_cog'] < thresh_delta_cog).mean(),
)

print(
    'Test dif below threshold:',
    (df['dif'] < thresh_dif).mean(),
)

print(
    'Test delta_dif below threshold:',
    (df['delta_dif'] < thresh_delta_dif).mean(),
)